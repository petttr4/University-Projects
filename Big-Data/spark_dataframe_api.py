from pyspark.sql import SparkSession
from pyspark.sql import functions as F
from pyspark.sql.types import FloatType, IntegerType
import time
import shutil

# Initialize Spark Session
spark = (SparkSession.builder
           .appName("Flights-DataFrame-Analysis")
           .master("local[*]")
           .getOrCreate())
sc = spark.sparkContext
print("SparkSession initiated")

from google.colab import files
import io

# 1)Διαβασμα αρχείου

print("\nΠαρακαλώ ανεβάστε το αρχείο flights_2000.csv")
uploaded = files.upload()
filename = next(iter(uploaded.keys()))
print(f"Το αρχείο '{filename}' φορτώθηκε επιτυχώς.")

OUTPUT_DIR = "top_routes_delays.csv"

# 1) Διαβασμα του flights_2000.csv ως DataFrame με Spark.

df = (spark.read.csv(filename, header=True, inferSchema=True)
      # Ασφαλής μετατροπή τύπων
      .withColumn("DEP_DELAY", F.col("DEP_DELAY").cast(FloatType()))
      .withColumn("CANCELLED", F.col("CANCELLED").cast(IntegerType()))
     )

# 2) Εμφανιση το schema του πίνακα με printSchema()
print("\n--- DataFrame Schema ---")
df.printSchema()

# 3) Φιλτράρετε τις εγγραφές και υπολογίστε

# Φιλτράρισμα και καθαρισμός
filtered_df = (df
               .filter(F.col("CANCELLED") == 0)
               .na.drop(subset=["DEP_DELAY"])
              )

# Δημιουργία της διαδρομής route ως μοναδικό πεδίο
routes_df = filtered_df.withColumn(
    "ROUTE",
    F.concat(F.col("ORIGIN_AIRPORT"), F.lit("-"), F.col("DEST_AIRPORT"))
)

# Υπολογισμός και τop-10
avg_delay_df = (routes_df
                .groupBy("ROUTE")
                .agg(F.avg("DEP_DELAY").alias("AvgDelay"))
                .orderBy(F.desc("AvgDelay"))
                .limit(10)
               )

# 5) Εκτέλεση και χρονομέτρηση (5 επαναλήψεις)

execution_times = []
first_action_times = []
last_results = None

print("\n--- Εκτέλεση DataFrame API (5 επαναλήψεις) ---")

for i in range(5):
    print(f"\n--- Εκτέλεση {i+1}/5 ---")

    # Χρονομέτρηση "πρώτου action": count()
    start_first_action = time.time()
    count_action = filtered_df.count()
    end_first_action = time.time()
    first_action_time = end_first_action - start_first_action
    first_action_times.append(first_action_time)
    print(f"Χρόνος Πρώτου Action (count): {first_action_time:.4f} δευτ.")

    # Χρονομέτρηση "συνολικού χρόνου", τελική Action (collect) για το top-10
    start_total = time.time()
    final_results = avg_delay_df.collect()
    end_total = time.time()
    total_time = end_total - start_total
    execution_times.append(total_time)
    last_results = final_results
    print(f"Συνολικός Χρόνος Εκτέλεσης (collect Top-10): {total_time:.4f} δευτ.")

# 4) Αποθηκεύστε το αποτέλεσμα σε αρχείο CSV με write.csv()

# Αφαίρεση προηγούμενης εξόδου (αν υπάρχει)
try:
    shutil.rmtree(OUTPUT_DIR)
    print(f"\nΑφαιρέθηκε ο προηγούμενος φάκελος {OUTPUT_DIR}/")
except FileNotFoundError:
    pass

# Αποθήκευση του DataFrame
avg_delay_df.write.csv(OUTPUT_DIR, header=True, mode="overwrite")
print(f"Τα Top-10 Routes αποθηκεύτηκαν επιτυχώς στον φάκελο: {OUTPUT_DIR}/")

# 5.a,b,c) Υπολογισμοί και εκτύπωση Αποτελεσμάτων

print("\n--- Αποτελέσματα Χρονομέτρησης & Υπολογισμοί (DataFrame API) ---")

# Ταξινόμηση και εύρεση των ενδιάμεσων 3 τιμών
sorted_total = sorted(execution_times)
sorted_first_action = sorted(first_action_times)

intermediate_total = sorted_total[1:-1]
intermediate_first_action = sorted_first_action[1:-1]

avg_total_time = sum(intermediate_total) / len(intermediate_total)
avg_first_action_time = sum(intermediate_first_action) / len(intermediate_first_action)

print("\n   Δείγμα Εξόδου (Top-10 Routes)")
print("| Route | Μέση Καθυστέρηση (λεπτά) |")
print("|:------|:-------------------------|")
for row in last_results:
    print(f"| {row.ROUTE} | {row.AvgDelay:.2f} |")
print("---------------------------------------")

print("\n    Πίνακας Χρόνων Εκτέλεσης (DataFrame API)")
print("| Εκτέλεση | Συνολικός Χρόνος (sec) | Χρόνος Πρώτου Action (sec) |")
print("|:---------|:-----------------------|:--------------------------|")
for i in range(5):
    print(f"| {i+1} | {execution_times[i]:.4f} | {first_action_times[i]:.4f} |")

print("\n--- Μέσοι Χρόνοι (3 ενδιάμεσες εκτελέσεις) ---")
print(f"| **Μέσος Συνολικός Χρόνος** | **{avg_total_time:.4f} sec** |")
print(f"| **Μέσος Χρόνος Πρώτου Action** | **{avg_first_action_time:.4f} sec** |")

