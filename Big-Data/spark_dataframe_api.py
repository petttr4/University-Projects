from pyspark.sql.types import FloatType, IntegerType
import seaborn as sns

# α. Δημιουργία της στήλης ωρα αναχώρησης (HOUR)
# Η SCHED_DEP είναι σε μορφή YYYY-MM-DD HH:MM οπότε παίρνουμε τις 2 ψηφιακές τιμές μετά τη θέση 11
# Το substr(12, 2) παίρνει τις ώρες (πχ από '2025-10-09 18:40' παίρνει '18')
df_with_hour = filtered_df.withColumn(
    "HOUR",
    F.substring(F.col("SCHED_DEP"), 12, 2).cast(IntegerType())
)

# Υπολογισμός μέσης καθυστέρησης ανά ωρα
avg_delay_by_hour = df_with_hour.groupBy("HOUR").agg(
    F.avg("DEP_DELAY").alias("AvgDelay")
).orderBy("HOUR")

# Μετατροπή σε pandas Dataframe για εύκολη οπτικοποίηση
pandas_df = avg_delay_by_hour.toPandas()

# Μετατροπή της στήλης 'HOUR' σε ακέραιο τύπο στο pandas Dataframe
pandas_df['HOUR'] = pandas_df['HOUR'].astype(int)

# Δημιουργία οπτικοποίησης
plt.figure(figsize=(12, 6))
sns.barplot(x="HOUR", y="AvgDelay", data=pandas_df, palette="viridis")
plt.title('Μέση Καθυστέρηση Αναχώρησης ανά Ώρα της Ημέρας')
plt.xlabel('Ώρα Αναχώρησης (24ωρο)')
plt.ylabel('Μέση Καθυστέρηση (λεπτά)')
plt.xticks(rotation=0)
plt.grid(axis='y', linestyle='--')
plt.show()

