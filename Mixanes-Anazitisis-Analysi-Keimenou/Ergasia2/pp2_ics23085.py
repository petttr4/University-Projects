punctuation = {".", "!", "?", ",", ";", ":"}

def apply_negation(tokens):
    negated = []
    negate = False

    for token in tokens:
        if token in punctuation:
            negate = False
            continue

        if token in negation_words or token.endswith("n't"):
            negate = True
            continue

        if negate:
            negated.append("NOT_" + token)
        else:
            negated.append(token)

    return negated

