#Συνάρτηση mean pooling
def document_mean_vector(tokens, w2v_model, vector_size):
    vectors = [w2v_model.wv[t] for t in tokens if t in w2v_model.wv]
    if len(vectors) == 0:
        return np.zeros(vector_size)
    return np.mean(vectors, axis=0)

